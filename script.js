/* =====================================================
   3. АККОРДЕОН
   Виконується ПІСЛЯ генерації розмітки, тому всі .faq-item вже існують у DOM.
===================================================== */
(function () {
  var reduceMotion = window.matchMedia('(prefers-reduced-motion: reduce)').matches;
  var items = Array.prototype.slice.call(document.querySelectorAll('.faq-item'));
  var toggleAllBtn = document.getElementById('toggleAll');

  // Відкриває або закриває одну панель з плавною зміною висоти
  function setOpen(item, open) {
    if (item.classList.contains('is-open') === open) return;

    var button = item.querySelector('.faq-question');
    var panel = item.querySelector('.faq-answer');

    button.setAttribute('aria-expanded', String(open));
    item.classList.toggle('is-open', open);

    // Без анімації (якщо користувач просив зменшити рух)
    if (reduceMotion) {
      panel.style.height = open ? 'auto' : '0px';
      return;
    }

    if (open) {
      // від поточної висоти до повної висоти вмісту
      panel.style.height = panel.scrollHeight + 'px';
    } else {
      // спочатку фіксуємо поточну висоту (auto не анімується), потім згортаємо до 0
      panel.style.height = panel.getBoundingClientRect().height + 'px';
      void panel.offsetHeight; // примусове перерахування стилів
      panel.style.height = '0px';
    }
  }

  function updateToggleAllLabel() {
    var allOpen = items.every(function (item) {
      return item.classList.contains('is-open');
    });
    toggleAllBtn.textContent = allOpen ? 'Згорнути все' : 'Розгорнути все';
  }

  items.forEach(function (item) {
    var button = item.querySelector('.faq-question');
    var panel = item.querySelector('.faq-answer');

    button.addEventListener('click', function () {
      setOpen(item, !item.classList.contains('is-open'));
      updateToggleAllLabel();
    });

    // Після завершення відкриття повертаємо height: auto,
    // щоб вміст коректно підлаштовувався під розмір вікна
    panel.addEventListener('transitionend', function (e) {
      if (e.target !== panel || e.propertyName !== 'height') return;
      if (item.classList.contains('is-open')) {
        panel.style.height = 'auto';
      }
    });
  });

  toggleAllBtn.addEventListener('click', function () {
    var shouldOpen = !items.every(function (item) {
      return item.classList.contains('is-open');
    });
    items.forEach(function (item) { setOpen(item, shouldOpen); });
    updateToggleAllLabel();
  });

  // Якщо змінюється розмір вікна — відкриті панелі підлаштовуються автоматично
  window.addEventListener('resize', function () {
    items.forEach(function (item) {
      if (item.classList.contains('is-open')) {
        item.querySelector('.faq-answer').style.height = 'auto';
      }
    });
  });
})();